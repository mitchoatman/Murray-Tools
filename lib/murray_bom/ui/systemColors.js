// Which model categories are colored by service: every element in a category whose name matches this
// (pipework, ductwork, hangers, containment...), plus the elements of the exports marked colorBy 'service'.
// Use /./ to color every category (slower on very large models).
var COLOR_CATEGORY_PATTERN = /fabrication/i;

function normalizeService(s) {
  return String(s === null || s === undefined ? '' : s).replace(/\s+/g, ' ').trim().toUpperCase();
}

// Same list with names normalised, ready for matching.
var SYSTEM_COLORS_BY_NAME = (function () {
  var m = {};
  Object.keys(SYSTEM_COLORS).forEach(function (k) { m[normalizeService(k)] = SYSTEM_COLORS[k]; });
  return m;
})();
